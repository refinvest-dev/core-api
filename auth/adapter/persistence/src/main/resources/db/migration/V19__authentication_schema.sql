-- Existing identity sequences, token fingerprints and refresh families remain untouched.
CREATE TABLE IF NOT EXISTS social_identities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider VARCHAR(20) NOT NULL,
    provider_subject VARCHAR(255) NOT NULL,
    member_id BIGINT NOT NULL,
    CONSTRAINT uk_social_identity_provider_subject UNIQUE (provider, provider_subject)
);
CREATE TABLE IF NOT EXISTS refresh_sessions (
    jti UUID PRIMARY KEY,
    member_id BIGINT NOT NULL,
    family_id UUID NOT NULL,
    token_fingerprint VARCHAR(128) NOT NULL,
    issued_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    replaced_by_jti UUID
);
