-- Match the existing JPA mappings; never rebuild immutable versions.
CREATE TABLE IF NOT EXISTS strategies (
    id BIGINT PRIMARY KEY,
    member_id BIGINT NOT NULL,
    name VARCHAR(200) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS strategy_versions (
    id BIGINT PRIMARY KEY,
    strategy_id BIGINT NOT NULL REFERENCES strategies(id),
    created_at TIMESTAMPTZ NOT NULL,
    primary_signal_asset VARCHAR(255) NOT NULL,
    execution_asset VARCHAR(255) NOT NULL,
    lag INTEGER NOT NULL,
    holding_signal_sessions INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS strategy_version_conditions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    strategy_version_id BIGINT NOT NULL REFERENCES strategy_versions(id),
    condition_order INTEGER NOT NULL,
    operator VARCHAR(255) NOT NULL,
    logical_combinator VARCHAR(255),
    operand_a_asset VARCHAR(255) NOT NULL,
    operand_a_metric VARCHAR(255) NOT NULL,
    operand_a_window INTEGER,
    operand_b_kind VARCHAR(255) NOT NULL,
    operand_b_literal DOUBLE PRECISION,
    operand_b_asset VARCHAR(255),
    operand_b_metric VARCHAR(255),
    operand_b_window INTEGER
);
